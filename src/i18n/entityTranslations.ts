export function formatLocalizedPriceByUnit(
  priceInQuintal: number,
  unit: 'quintal' | 'kg' | 'tonne',
  lang: SupportedLanguage = 'en'
): { value: number; label: string; formatted: string; rawPriceStr: string } {
  const unitInfo = UNIT_LOCALIZED_LABELS[unit]?.[lang] || UNIT_LOCALIZED_LABELS[unit]?.en || { short: '₹/Quintal', suffix: 'Quintal' };

  if (unit === 'kg') {
    const val = priceInQuintal / 100;
    return {
      value: val,
      label: unitInfo.short,
      rawPriceStr: `₹${val.toFixed(2)}`,
      formatted: `₹${val.toFixed(2)} / ${unitInfo.suffix}`
    };
  }
  if (unit === 'tonne') {
    const val = priceInQuintal * 10;
    return {
      value: val,
      label: unitInfo.short,
      rawPriceStr: `₹${val.toLocaleString('en-IN')}`,
      formatted: `₹${val.toLocaleString('en-IN')} / ${unitInfo.suffix}`
    };
  }

  // Default quintal
  return {
    value: priceInQuintal,
    label: unitInfo.short,
    rawPriceStr: `₹${priceInQuintal.toLocaleString('en-IN')}`,
    formatted: `₹${priceInQuintal.toLocaleString('en-IN')} / ${unitInfo.suffix}`
  };
}
